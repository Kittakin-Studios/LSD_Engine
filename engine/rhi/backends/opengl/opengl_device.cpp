    void draw_ui(const UiDraw& d) override {
        const u32 vbytes = d.vertex_count * static_cast<u32>(sizeof(UiVertex));
        const u32 ibytes = d.index_count * 4u;
        if (!d.vertex_count || !d.index_count || vbytes > kParticleRingBytes || ibytes > kUiIndexBytes) return;
        if (particle_offset_ + vbytes > kParticleRingBytes) particle_offset_ = 0;
        if (ui_index_offset_ + ibytes > kUiIndexBytes) ui_index_offset_ = 0;
        gl_.glNamedBufferSubData(particle_vbo_, particle_offset_, vbytes, d.vertices);
        gl_.glNamedBufferSubData(ui_ibo_, ui_index_offset_, ibytes, d.indices);
        const Texture* t = lookup_texture(d.texture);
        glDisable(GL_DEPTH_TEST);
        glDepthMask(GL_FALSE);
        glEnable(GL_BLEND);
        gl_.glBlendFuncSeparate(GL_ONE, GL_ONE_MINUS_SRC_ALPHA, GL_ONE, GL_ONE_MINUS_SRC_ALPHA);
        // The UI's rectangle (top-left origin) in GL's bottom-left window coordinates.
        const GLint gl_y = static_cast<GLint>(static_cast<f32>(target_height_) - d.viewport[1] - d.viewport[3]);
        glViewport(static_cast<GLint>(d.viewport[0]), gl_y, static_cast<GLsizei>(d.viewport[2]), static_cast<GLsizei>(d.viewport[3]));
        if (d.scissor[2] > 0) {
            glScissor(static_cast<GLint>(d.viewport[0]) + d.scissor[0], gl_y + static_cast<GLint>(d.viewport[3]) - d.scissor[1] - d.scissor[3], d.scissor[2], d.scissor[3]);
        } else {
            glScissor(static_cast<GLint>(d.viewport[0]), gl_y, static_cast<GLsizei>(d.viewport[2]), static_cast<GLsizei>(d.viewport[3]));
        }
        gl_.glUseProgram(ui_program_);
        const f32 draw[4] = {d.translation[0], d.translation[1], 2.0f / d.viewport[2], 2.0f / d.viewport[3]};
        gl_.glUniform4fv(ui_draw_, 1, draw);
        gl_.glBindTextureUnit(0, t ? t->id : textures_[white_].id);
        gl_.glVertexArrayVertexBuffer(ui_vao_, 0, particle_vbo_, particle_offset_, sizeof(UiVertex));
        gl_.glVertexArrayElementBuffer(ui_vao_, ui_ibo_);
        gl_.glBindVertexArray(ui_vao_);
        glDrawElements(GL_TRIANGLES, static_cast<GLsizei>(d.index_count), GL_UNSIGNED_INT, reinterpret_cast<const void*>(static_cast<uintptr_t>(ui_index_offset_)));
        particle_offset_ += (vbytes + 255u) & ~255u;
        ui_index_offset_ += (ibytes + 255u) & ~255u;
        glDisable(GL_BLEND);
        glDepthMask(GL_TRUE);
        glEnable(GL_DEPTH_TEST);
        set_viewport(viewport_[0], static_cast<f32>(target_height_) - viewport_[1] - viewport_[3], viewport_[2], viewport_[3]);  // the caller's rectangle again
    }

    PostChain& post_chain(u32 width, u32 height) {
        for (PostChain& c : post_chains_) {
            if (c.width == width && c.height == height) return c;
        }
        PostChain& c = post_chains_[post_chain_next_++ % 4];
        for (TextureHandle& t : c.down) destroy_texture(t);
        for (TextureHandle& t : c.up) destroy_texture(t);
        for (TextureHandle& t : c.taa) destroy_texture(t);
        destroy_texture(c.ao);
        destroy_texture(c.lit);
        destroy_texture(c.dof);
        destroy_texture(c.motion);
        destroy_texture(c.velocity);
        destroy_texture(c.ssr);
        destroy_texture(c.ldr);
        for (TextureHandle& t : c.exposure) destroy_texture(t);
        destroy_texture(c.exposed);
        c = PostChain{};
        c.width = width;
        c.height = height;
        for (u32 i = 0; i < 5; ++i) {
            const u32 w = (width >> (i + 1)) ? (width >> (i + 1)) : 1u, h = (height >> (i + 1)) ? (height >> (i + 1)) : 1u;
            c.down[i] = create_render_target(w, h);
            if (i < 4) c.up[i] = create_render_target(w, h);
        }
        c.ldr = create_render_target(width, height);
        c.ao = create_render_target(width, height);  // shortcut: full-size effect targets even when unused; make them lazily if memory gets tight
        c.lit = create_render_target(width, height);
        c.dof = create_render_target(width, height);
        c.motion = create_render_target(width, height);
        c.velocity = create_render_target(width, height);
        c.ssr = create_render_target(width, height);
        c.taa[0] = create_render_target(width, height);
        c.taa[1] = create_render_target(width, height);
        c.exposure[0] = create_render_target(1, 1);
        c.exposure[1] = create_render_target(1, 1);
        c.exposed = create_render_target(width, height);
        return c;
    }
    // One full-screen pass into `target` (invalid: the window, in `window_rect`); `depth_of`: whose depth is t2.
    // `custom`: a post-process material's composite instead of `program`'s.
    void post_pass(int program, TextureHandle target, const f32* window_rect, TextureHandle in0, TextureHandle in1, TextureHandle depth_of, const f32 constants[48],
                   bool blend = false, const PostShader* custom = nullptr, bool color2 = false) {  // color2: in2's colour, not its depth
        const f32 black[4] = {0, 0, 0, 1};
        if (target.valid()) {
            set_render_target(target, black);
        } else {
            set_render_target({}, nullptr);
            set_viewport(window_rect[0], window_rect[1], window_rect[2], window_rect[3]);
        }
        glDisable(GL_DEPTH_TEST);
        if (blend) {  // over what is there (the outline)
            glEnable(GL_BLEND);
            glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
        } else {
            glDisable(GL_BLEND);
        }
        const Target* a = lookup(in0);
        const Target* b = lookup(in1);
        gl_.glUseProgram(custom ? custom->program : post_programs_[program]);
        const Target* d = lookup(depth_of);
        gl_.glUniform4fv(custom ? custom->uniform : post_uniforms_[program], 12, constants);
        gl_.glBindTextureUnit(0, a ? a->color : textures_[white_].id);
        gl_.glBindTextureUnit(1, b ? b->color : textures_[white_].id);
        const Texture* plain = d ? nullptr : lookup_texture(depth_of);  // not a target: an ordinary texture (the Color Grading LUT)
        gl_.glBindTextureUnit(2, d ? (color2 ? d->color : d->depth) : plain ? plain->id : textures_[white_].id);
        gl_.glBindVertexArray(vao_);
        glDrawArrays(GL_TRIANGLES, 0, 3);
    }

    bool read_render_target(TextureHandle handle, u8* rgba) override {
        const Target* t = lookup(handle);
        if (!t) return false;
        const usize row = static_cast<usize>(t->width) * 4;
        glPixelStorei(GL_PACK_ALIGNMENT, 1);
        gl_.glGetTextureImage(t->color, 0, GL_RGBA, GL_UNSIGNED_BYTE, static_cast<GLsizei>(row * t->height), rgba);
        std::vector<u8> swap(row);  // GL rows run bottom-up: flip to top-down
        for (u32 y = 0; y < t->height / 2; ++y) {
            u8* a = rgba + y * row;
            u8* b = rgba + (t->height - 1 - y) * row;
            std::memcpy(swap.data(), a, row);
            std::memcpy(a, b, row);
            std::memcpy(b, swap.data(), row);
        }
        return true;
    }

    // The Hi-Z from a scene target's depth: half its size, then halving to 1 x 1 (each the farthest of 2 x 2).
    void build_hiz(GLuint scene_depth, u32 scene_width, u32 scene_height, const f32 view_proj[16]) {
        if (!hiz_program_) return;
        const u32 w = scene_width > 1 ? (scene_width + 1) / 2 : 1, h = scene_height > 1 ? (scene_height + 1) / 2 : 1;
        u32 mips = 1;
        while ((std::max(w, h) >> mips) > 0) ++mips;
        if (!hiz_texture_ || hiz_size_[0] != w || hiz_size_[1] != h) {
            if (hiz_texture_) glDeleteTextures(1, &hiz_texture_);
            gl_.glCreateTextures(GL_TEXTURE_2D, 1, &hiz_texture_);
            gl_.glTextureStorage2D(hiz_texture_, static_cast<GLsizei>(mips), GL_R32F, static_cast<GLsizei>(w), static_cast<GLsizei>(h));
            hiz_size_[0] = w;
            hiz_size_[1] = h;
            hiz_mips_ = mips;
        }
        gl_.glUseProgram(hiz_program_);
        u32 sw = scene_width, sh = scene_height;
        for (u32 m = 0; m < mips; ++m) {
            const u32 dw = std::max(w >> m, 1u), dh = std::max(h >> m, 1u);
            gl_.glBindTextureUnit(0, m ? hiz_texture_ : scene_depth);
            gl_.glBindImageTexture(0, hiz_texture_, static_cast<GLint>(m), GL_FALSE, 0, GL_WRITE_ONLY, GL_R32F);
            gl_.glUniform4i(hiz_size_location_, static_cast<GLint>(dw), static_cast<GLint>(dh), static_cast<GLint>(sw), static_cast<GLint>(sh));
            gl_.glUniform1i(hiz_level_location_, m ? static_cast<GLint>(m - 1) : 0);
            gl_.glDispatchCompute((dw + 7) / 8, (dh + 7) / 8, 1);
            gl_.glMemoryBarrier(GL_TEXTURE_FETCH_BARRIER_BIT | GL_SHADER_IMAGE_ACCESS_BARRIER_BIT);
            sw = dw;
            sh = dh;
        }
        std::memcpy(hiz_view_proj_, view_proj, sizeof hiz_view_proj_);
        hiz_valid_ = true;
    }

    void draw_post(const PostDraw& p) override {
        if (const Target* depth_of = lookup(p.scene); depth_of && p.build_hiz) build_hiz(depth_of->depth, depth_of->width, depth_of->height, p.hiz_view_proj);  // the next frame's occlusion test
        Target* scene = lookup(p.scene);
        if (!scene) return;
        PostChain& c = post_chain(scene->width, scene->height);
        auto size = [&](TextureHandle t, f32* out) {
            const Target* target = lookup(t);
            out[0] = target ? 1.0f / static_cast<f32>(target->width) : 0.0f;
            out[1] = target ? 1.0f / static_cast<f32>(target->height) : 0.0f;
        };
        const bool depth_effects = p.proj[0] != 0.0f;
        const bool ao = depth_effects && (p.ao_intensity > 0.0f || p.contact_shadow[3] > 0.0f);
        const bool dof = depth_effects && p.dof_focal_distance > 0.0f;
        const bool motion = depth_effects && p.motion_blur > 0.0f && !p.taa_reset;
        const bool taa = depth_effects && p.taa;
        const bool ssr = depth_effects && p.ssr_intensity > 0.0f;
        if (!taa) c.history_valid = false;
        f32 k[48] = {};  // the constants every pass reads (see the shaders' u_post / cbuffer Post)
        for (int i = 0; i < 4; ++i) k[16 + i] = p.proj[i];
        k[20] = p.ao_radius > 0.01f ? p.ao_radius : 0.01f;
        k[21] = p.ao_intensity;
        k[22] = p.ssr_intensity;
        k[23] = p.ssr_max_distance > 0.5f ? p.ssr_max_distance : 0.5f;
        k[24] = p.dof_focal_distance;
        k[25] = p.dof_focal_region;
        k[26] = p.dof_max_blur;
        k[27] = p.dof_transition;
        k[28] = 0.1f;  // TAA: how much of this frame goes in
        k[29] = (p.taa_reset || !c.history_valid) ? 1.0f : 0.0f;
        k[30] = p.motion_blur;
        k[31] = p.motion_blur_max;
        for (int r = 0; r < 4; ++r) {
            for (int col = 0; col < 4; ++col) k[32 + r * 4 + col] = p.reproject[col * 4 + r];  // rows
        }
        size(p.scene, k);
        k[2] = lookup(p.normals) ? 1.0f : 0.0f;  // SSR / AO: normals from the normals pass (t1)
        TextureHandle src = p.scene;
        if (ssr) {  // first: it reads the scene's alpha (reflectivity)
            post_pass(9, c.ssr, nullptr, p.scene, p.normals, p.scene, k);
            src = c.ssr;
        }
        if (ao) {
            f32 ka[48];  // the AO pass reads no reprojection: its first row carries the contact shadow ray
            std::memcpy(ka, k, sizeof ka);
            std::memcpy(ka + 32, p.contact_shadow, sizeof p.contact_shadow);
            post_pass(5, c.ao, nullptr, {}, p.normals, p.scene, ka);
            post_pass(6, c.lit, nullptr, src, c.ao, p.scene, k);
            src = c.lit;
        }
        // The velocity pass (objects' own movement): resolved with the camera's where nothing was drawn, for TAA and motion blur.
        const bool vel = (taa || motion) && lookup(p.velocity);
        f32 kv[48];
        std::memcpy(kv, k, sizeof kv);
        kv[3] = 1.0f;  // texel.w: they read it
        if (vel) post_pass(14, c.velocity, nullptr, {}, p.velocity, p.scene, k);
        if (taa) {
            const TextureHandle out = c.taa[c.taa_index], history = c.taa[c.taa_index ^ 1u];
            post_pass(7, out, nullptr, src, history, vel ? c.velocity : p.scene, vel ? kv : k, false, nullptr, vel);
            c.taa_index ^= 1u;
            c.history_valid = true;
            src = out;
        }
        if (dof) {
            post_pass(8, c.dof, nullptr, src, {}, p.scene, k);
            src = c.dof;
        }
        if (motion) {
            post_pass(13, c.motion, nullptr, src, vel ? c.velocity : TextureHandle{}, p.scene, vel ? kv : k);
            src = c.motion;
        }
        if (p.auto_exposure) {  // eye adaptation: meter into 1 x 1 (eased from the last frame's), then apply it
            f32 e[48] = {};
            e[4] = p.exposure_min_ev;
            e[5] = p.exposure_max_ev;
            e[6] = p.exposure_compensation;
            e[7] = c.exposure_valid && p.delta_seconds > 0.0f ? 0.0f : 1.0f;  // 1: jump to the target
            e[8] = p.delta_seconds * p.exposure_speed_up;
            e[9] = p.delta_seconds * p.exposure_speed_down;
            const TextureHandle now = c.exposure[c.exposure_index], last = c.exposure[c.exposure_index ^ 1u];
            post_pass(10, now, nullptr, src, last, {}, e);
            post_pass(11, c.exposed, nullptr, src, now, {}, e);
            c.exposure_index ^= 1u;
            c.exposure_valid = true;
            src = c.exposed;
        } else {
            c.exposure_valid = false;
        }
        const bool bloom = p.bloom_intensity > 0.0f;
        if (bloom) {
            k[4] = p.bloom_threshold;
            size(src, k);
            post_pass(0, c.down[0], nullptr, src, {}, {}, k);
            for (u32 i = 1; i < 5; ++i) {
                size(c.down[i - 1], k);
                post_pass(1, c.down[i], nullptr, c.down[i - 1], {}, {}, k);
            }
            for (i32 i = 3; i >= 0; --i) {  // up[i] = down[i] + blur(up[i + 1]); the lowest uses down[4]
                const TextureHandle below = i == 3 ? c.down[4] : c.up[i + 1];
                size(c.down[i], k);
                size(below, k + 2);
                post_pass(2, c.up[i], nullptr, c.down[i], below, {}, k);
            }
        }
        f32 g[48] = {};
        g[5] = bloom ? p.bloom_intensity : 0.0f;
        g[8] = p.tint[0];
        g[9] = p.tint[1];
        g[10] = p.tint[2];
        g[11] = p.tonemap ? 1.0f : 0.0f;
        g[12] = p.saturation;
        g[13] = p.contrast;
        g[14] = p.vignette;
        g[15] = p.color_lut.valid() ? p.lut_intensity : 0.0f;
        post_color_vision(p, g);
        const bool fxaa = p.fxaa && !taa;
        const PostShader* custom = lookup_post(p.post_shader);
        if (custom) {  // a post-process material: the scene's texel, its time and parameters (proj's row: unused here)
            size(src, g);
            g[16] = p.post_time;
            for (int n = 0; n < 3; ++n) g[17 + n] = p.post_params[n];
        }
        post_pass(3, fxaa ? c.ldr : p.output, p.viewport, src, bloom ? c.up[0] : TextureHandle{}, p.color_lut, g, false, custom);
        if (fxaa) {
            f32 f[48] = {};
            size(c.ldr, f);
            post_pass(4, p.output, p.viewport, c.ldr, {}, {}, f);
        }
        glEnable(GL_DEPTH_TEST);
        set_viewport(p.viewport[0], p.viewport[1], p.viewport[2], p.viewport[3]);
    }

    void draw_outline(const MeshDraw* draws, u32 count, const f32 color[4], const f32 viewport[4]) override {
        const u32 w = static_cast<u32>(viewport[2]), h = static_cast<u32>(viewport[3]);
        if (!count || !w || !h) return;
        if (outline_size_[0] != w || outline_size_[1] != h) {  // the mask: one per viewport size, kept
            destroy_texture(outline_mask_);
            outline_mask_ = create_render_target(w, h);
            outline_size_[0] = w;
            outline_size_[1] = h;
        }
        const f32 clear[4] = {0, 0, 0, 0};
        set_render_target(outline_mask_, clear);
        for (u32 i = 0; i < count; ++i) {  // each as plain white: only where it covers matters
            MeshDraw d = draws[i];
            d.unlit = true;
            d.wireframe = false;
            d.debug_view = 0;
            d.blend = 0;
            d.alpha_cutoff = 0.0f;
            d.material_shader = {};
            d.base_color_texture = {};
            d.color[0] = d.color[1] = d.color[2] = d.color[3] = 1.0f;
            draw_mesh(d);
        }
        f32 k[48] = {};
        k[0] = 1.0f / static_cast<f32>(w);
        k[1] = 1.0f / static_cast<f32>(h);
        for (int c = 0; c < 4; ++c) k[8 + c] = color[c];
        post_pass(12, {}, viewport, outline_mask_, {}, {}, k, true);
        glDisable(GL_BLEND);
        glEnable(GL_DEPTH_TEST);
        set_viewport(viewport[0], viewport[1], viewport[2], viewport[3]);
    }

