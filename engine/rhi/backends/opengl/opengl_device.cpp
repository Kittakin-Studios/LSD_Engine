        bool ok = true;
#define LSD_GL_LOAD(type, name)                                                     \
        name = reinterpret_cast<type>(SDL_GL_GetProcAddress(#name));               \
        if (!name) { LSD_LOG_ERROR("opengl", "Missing function %s", #name); ok = false; }
