    Texture* lookup_texture(TextureHandle handle) {
        if (!handle.valid() || handle.index() < kMaxTargets || handle.index() >= kMaxTargets + kMaxTextures) return nullptr;
        Texture& t = textures_[handle.index() - kMaxTargets];
        if (!t.id || (t.generation & TextureHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &t;
    }

    struct ShadowMap {
        GLuint texture = 0;
        GLuint fbo = 0;
        u32 size = 0;
        u32 generation = 0;
    };

    ShadowMap* lookup_shadow(TextureHandle handle) {
        const u32 first = kMaxTargets + kMaxTextures;
        if (!handle.valid() || handle.index() < first || handle.index() >= first + kMaxShadowMaps) return nullptr;
        ShadowMap& m = shadow_maps_[handle.index() - first];
        if (!m.texture || (m.generation & TextureHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &m;
    }

    Target* lookup(TextureHandle handle) {
        if (!handle.valid() || handle.index() >= kMaxTargets) return nullptr;
        Target& t = targets_[handle.index()];
        if (!t.fbo || (t.generation & TextureHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &t;
    }

    void release_target(Target& t) {
        if (t.fbo) gl_.glDeleteFramebuffers(1, &t.fbo);
        if (t.depth) glDeleteTextures(1, &t.depth);
        if (t.color) glDeleteTextures(1, &t.color);
        t.fbo = t.depth = t.color = 0;
    }

    Buffer* lookup(BufferHandle handle) {
        if (!handle.valid() || handle.index() >= kMaxBuffers) return nullptr;
        Buffer& b = buffers_[handle.index()];
        if (!b.id || (b.generation & BufferHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &b;
    }

    GLuint link(const char* vertex_source, const char* fragment_source) {
        const GLuint vs = compile(GL_VERTEX_SHADER, vertex_source);
        const GLuint fs = compile(GL_FRAGMENT_SHADER, fragment_source);
        if (!vs || !fs) return 0;
        const GLuint program = gl_.glCreateProgram();
        gl_.glAttachShader(program, vs);
        gl_.glAttachShader(program, fs);
        gl_.glLinkProgram(program);
        gl_.glDeleteShader(vs);
        gl_.glDeleteShader(fs);
        GLint ok = 0;
        gl_.glGetProgramiv(program, GL_LINK_STATUS, &ok);
        if (!ok) {
            char log[1024];
            gl_.glGetProgramInfoLog(program, sizeof log, nullptr, log);
            LSD_LOG_ERROR("opengl", "Program link failed: %s", log);
            gl_.glDeleteProgram(program);
            return 0;
        }
        return program;
    }

