Vendor vendor_from_string(const char* vendor) {
    if (std::strstr(vendor, "NVIDIA")) return Vendor::Nvidia;
    if (std::strstr(vendor, "AMD") || std::strstr(vendor, "ATI")) return Vendor::Amd;
    if (std::strstr(vendor, "Intel")) return Vendor::Intel;
    return Vendor::Other;
}

