// shortcut: hand-written GLSL mirror of the HLSL test triangle; generated by SPIRV-Cross from the
// HLSL source once the data compiler builds shaders.
constexpr char kVertexShader[] = R"(#version 460 core
uniform vec3 params;  // scale, angle, aspect
out vec3 v_color;
const vec2 kPos[3]   = vec2[3](vec2(0.0, 0.6), vec2(0.55, -0.5), vec2(-0.55, -0.5));
const vec3 kColor[3] = vec3[3](vec3(1, 0.2, 0.2), vec3(0.2, 1, 0.2), vec3(0.2, 0.4, 1));
void main() {
    float s = sin(params.y), c = cos(params.y);
    vec2 p = kPos[gl_VertexID] * params.x;
    p = vec2(c * p.x - s * p.y, s * p.x + c * p.y);
    gl_Position = vec4(p.x / params.z, p.y, 0.0, 1.0);
    v_color = kColor[gl_VertexID];
}
)";

constexpr char kFragmentShader[] = R"(#version 460 core
in vec3 v_color;
out vec4 o_color;
void main() { o_color = vec4(v_color, 1.0); }
)";

// Built-in lit mesh and line programs; mirror the HLSL in the D3D12 backend.
constexpr char kMeshVertexShader[] = R"(#version 460 core
layout(location = 0) in vec3 a_pos;
layout(location = 1) in vec3 a_normal;
layout(location = 2) in vec2 a_uv;
uniform mat4 u_mvp;
uniform vec4 u_rot[3];
out vec3 v_normal;
void main() {
    gl_Position = u_mvp * vec4(a_pos, 1.0);
    v_normal = u_rot[0].xyz * a_normal.x + u_rot[1].xyz * a_normal.y + u_rot[2].xyz * a_normal.z;
}
)";

constexpr char kMeshFragmentShader[] = R"(#version 460 core
uniform vec4 u_color;
uniform float u_unlit;
in vec3 v_normal;
out vec4 o_color;
void main() {
    if (u_unlit > 0.5) { o_color = u_color; return; }
    vec3 n = normalize(v_normal);
    vec3 sun = normalize(vec3(-0.5, -0.35, 0.8));
    float ambient = 0.25 + 0.1 * n.z;
    o_color = vec4(u_color.rgb * (ambient + 0.85 * clamp(dot(n, sun), 0.0, 1.0)), u_color.a);
}
)";

constexpr char kLineVertexShader[] = R"(#version 460 core
layout(location = 0) in vec3 a_pos;
layout(location = 1) in vec4 a_color;
uniform mat4 u_mvp;
out vec4 v_color;
void main() { gl_Position = u_mvp * vec4(a_pos, 1.0); v_color = a_color; }
)";

constexpr char kLineFragmentShader[] = R"(#version 460 core
in vec4 v_color;
out vec4 o_color;
void main() { o_color = v_color; }
)";

constexpr u32 kMaxBuffers = 4096;
constexpr u32 kMaxTargets = 256;

