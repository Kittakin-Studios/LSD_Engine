    GLuint compile(GLenum stage, const char* source) {
        const GLuint shader = gl_.glCreateShader(stage);
        gl_.glShaderSource(shader, 1, &source, nullptr);
        gl_.glCompileShader(shader);
        GLint ok = 0;
        gl_.glGetShaderiv(shader, GL_COMPILE_STATUS, &ok);
        if (!ok) {
            char log[1024];
            gl_.glGetShaderInfoLog(shader, sizeof log, nullptr, log);
            LSD_LOG_ERROR("opengl", "Shader compile failed: %s", log);
            gl_.glDeleteShader(shader);
            return 0;
        }
        return shader;
    }

    struct Buffer {
        GLuint id = 0;
        BufferUsage usage = BufferUsage::Vertex;
        u32 generation = 0;
    };

    struct Target {
        GLuint fbo = 0;
        GLuint color = 0;
        GLuint depth = 0;
        u32 width = 0;
        u32 height = 0;
        u32 generation = 0;
    };

    struct Texture {
        GLuint id = 0;
        u32 generation = 0;
    };

    Texture* lookup_texture(TextureHandle handle) {
        if (!handle.valid() || handle.index() < kMaxTargets || handle.index() >= kMaxTargets + kMaxTextures) return nullptr;
        Texture& t = textures_[handle.index() - kMaxTargets];
        if (!t.id || (t.generation & TextureHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &t;
    }

    struct ShadowMap {
        GLuint texture = 0;
        GLuint fbo = 0;
        u32 size = 0;
        u32 generation = 0;
    };

    ShadowMap* lookup_shadow(TextureHandle handle) {
        const u32 first = kMaxTargets + kMaxTextures;
        if (!handle.valid() || handle.index() < first || handle.index() >= first + kMaxShadowMaps) return nullptr;
        ShadowMap& m = shadow_maps_[handle.index() - first];
        if (!m.texture || (m.generation & TextureHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &m;
    }

    Target* lookup(TextureHandle handle) {
        if (!handle.valid() || handle.index() >= kMaxTargets) return nullptr;
        Target& t = targets_[handle.index()];
        if (!t.fbo || (t.generation & TextureHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &t;
    }

    void release_target(Target& t) {
        if (t.fbo) gl_.glDeleteFramebuffers(1, &t.fbo);
        if (t.depth) glDeleteTextures(1, &t.depth);
        if (t.color) glDeleteTextures(1, &t.color);
        t.fbo = t.depth = t.color = 0;
    }

    Buffer* lookup(BufferHandle handle) {
        if (!handle.valid() || handle.index() >= kMaxBuffers) return nullptr;
        Buffer& b = buffers_[handle.index()];
        if (!b.id || (b.generation & BufferHandle::kGenerationMask) != handle.generation()) return nullptr;
        return &b;
    }

    GLuint link(const char* vertex_source, const char* fragment_source) {
        const GLuint vs = compile(GL_VERTEX_SHADER, vertex_source);
        const GLuint fs = compile(GL_FRAGMENT_SHADER, fragment_source);
        if (!vs || !fs) return 0;
        const GLuint program = gl_.glCreateProgram();
        gl_.glAttachShader(program, vs);
        gl_.glAttachShader(program, fs);
        gl_.glLinkProgram(program);
        gl_.glDeleteShader(vs);
        gl_.glDeleteShader(fs);
        GLint ok = 0;
        gl_.glGetProgramiv(program, GL_LINK_STATUS, &ok);
        if (!ok) {
            char log[1024];
            gl_.glGetProgramInfoLog(program, sizeof log, nullptr, log);
            LSD_LOG_ERROR("opengl", "Program link failed: %s", log);
            gl_.glDeleteProgram(program);
            return 0;
        }
        return program;
    }

    // Describes one float vertex attribute on binding 0 of a VAO.
    void attribute(GLuint vao, GLuint location, GLint components, GLuint offset) {
        gl_.glEnableVertexArrayAttrib(vao, location);
        gl_.glVertexArrayAttribFormat(vao, location, components, GL_FLOAT, GL_FALSE, offset);
        gl_.glVertexArrayAttribBinding(vao, location, 0);
    }

    bool create_programs() {
        program_ = link(kVertexShader, kFragmentShader);
        mesh_.id = link(with_skinning(kMeshVertexShader, false).c_str(), kMeshFragmentShader);
        skinned_program_.id = link(with_skinning(kMeshVertexShader, true).c_str(), kMeshFragmentShader);
        {
            std::string instanced = with_skinning(kMeshVertexShader, false);
            instanced.insert(instanced.find('\n') + 1, "#define INSTANCED\n");
            instanced_program_.id = link(instanced.c_str(), kMeshFragmentShader);
        }
        mesh_program_ = mesh_.id;
        if (const GLuint cs = compile(GL_COMPUTE_SHADER, kCullComputeShader)) {  // GPU culling (optional: without it every instance draws)
            cull_program_ = gl_.glCreateProgram();
            gl_.glAttachShader(cull_program_, cs);
            gl_.glLinkProgram(cull_program_);
            gl_.glDeleteShader(cs);
            GLint linked = 0;
            gl_.glGetProgramiv(cull_program_, GL_LINK_STATUS, &linked);
            if (!linked) {
                gl_.glDeleteProgram(cull_program_);
                cull_program_ = 0;
            }
            cull_pass_ = cull_program_ ? gl_.glGetUniformLocation(cull_program_, "u_pass") : -1;
        }
        if (const GLuint cs = cull_program_ ? compile(GL_COMPUTE_SHADER, kHizComputeShader) : 0) {  // the Hi-Z (optional: without it no occlusion test)
            hiz_program_ = gl_.glCreateProgram();
            gl_.glAttachShader(hiz_program_, cs);
            gl_.glLinkProgram(hiz_program_);
            gl_.glDeleteShader(cs);
            GLint linked = 0;
            gl_.glGetProgramiv(hiz_program_, GL_LINK_STATUS, &linked);
            if (!linked) {
                gl_.glDeleteProgram(hiz_program_);
                hiz_program_ = 0;
            }
            hiz_size_location_ = hiz_program_ ? gl_.glGetUniformLocation(hiz_program_, "u_size") : -1;
            hiz_level_location_ = hiz_program_ ? gl_.glGetUniformLocation(hiz_program_, "u_level") : -1;
        }
        if (const GLuint cs = compile(GL_COMPUTE_SHADER, kMorphComputeShader)) {  // morph targets (optional: else on the CPU)
            morph_program_ = gl_.glCreateProgram();
            gl_.glAttachShader(morph_program_, cs);
            gl_.glLinkProgram(morph_program_);
            gl_.glDeleteShader(cs);
            GLint linked = 0;
            gl_.glGetProgramiv(morph_program_, GL_LINK_STATUS, &linked);
            if (!linked) {
                gl_.glDeleteProgram(morph_program_);
                morph_program_ = 0;
            } else {
                gl_.glCreateBuffers(1, &morph_weights_);
                gl_.glNamedBufferStorage(morph_weights_, 16 + kMaxMorphTargets * 4, nullptr, GL_DYNAMIC_STORAGE_BIT);
            }
        }
        if (const GLuint cs = compile(GL_COMPUTE_SHADER, kGpuParticleSimShader)) {  // GPU particles (optional: else on the CPU)
            gpu_sim_program_ = gl_.glCreateProgram();
            gl_.glAttachShader(gpu_sim_program_, cs);
            gl_.glLinkProgram(gpu_sim_program_);
            gl_.glDeleteShader(cs);
            GLint linked = 0;
            gl_.glGetProgramiv(gpu_sim_program_, GL_LINK_STATUS, &linked);
            if (linked) gpu_sprite_program_ = link(kGpuParticleVertexShader, kParticleFragmentShader);
            if (!linked || !gpu_sprite_program_) {
                gl_.glDeleteProgram(gpu_sim_program_);
                gpu_sim_program_ = 0;
            } else {
                gpu_sprite_mvp_ = gl_.glGetUniformLocation(gpu_sprite_program_, "u_mvp");
                gpu_sprite_hdr_ = gl_.glGetUniformLocation(gpu_sprite_program_, "u_hdr");
                gpu_sprite_soft_ = gl_.glGetUniformLocation(gpu_sprite_program_, "u_soft");
                gl_.glCreateBuffers(1, &gpu_particle_ubo_);
                gl_.glNamedBufferStorage(gpu_particle_ubo_, sizeof(GpuParticles), nullptr, GL_DYNAMIC_STORAGE_BIT);
            }
        }
        line_program_ = link(kLineVertexShader, kLineFragmentShader);
        shadow_program_ = link(with_skinning(kShadowVertexShader, false).c_str(), kShadowFragmentShader);
        shadow_mvp_ = gl_.glGetUniformLocation(shadow_program_, "u_mvp");
        {
            std::string instanced = with_skinning(kShadowVertexShader, false);
            instanced.insert(instanced.find('\n') + 1, "#define INSTANCED\n");
            instanced_shadow_program_ = link(instanced.c_str(), kShadowFragmentShader);
            if (!instanced_shadow_program_) return false;
            instanced_shadow_mvp_ = gl_.glGetUniformLocation(instanced_shadow_program_, "u_mvp");
        }
        skinned_shadow_program_ = link(with_skinning(kShadowVertexShader, true).c_str(), kShadowFragmentShader);
        skinned_shadow_mvp_ = gl_.glGetUniformLocation(skinned_shadow_program_, "u_mvp");
        for (int k = 0; k < 2; ++k) {  // Masked casters: static, skinned
            cutout_shadow_program_[k] = link(with_skinning(kShadowVertexShader, k == 1).c_str(), kCutoutShadowFragmentShader);
            if (!cutout_shadow_program_[k]) return false;
            cutout_shadow_mvp_[k] = gl_.glGetUniformLocation(cutout_shadow_program_[k], "u_mvp");
            cutout_shadow_cut_[k] = gl_.glGetUniformLocation(cutout_shadow_program_[k], "u_cut");
        }
        if (!skinned_program_.id || !instanced_program_.id || !shadow_program_ || !skinned_shadow_program_) return false;
        if (!program_ || !mesh_program_ || !line_program_) return false;
        params_location_ = gl_.glGetUniformLocation(program_, "params");
        for (MeshProgram* p : {&mesh_, &skinned_program_, &instanced_program_}) locate(*p);
        // Defaults for meshes without textures: white (colour, occlusion / roughness / metallic) and a flat normal.
        const u32 white = 0xFFFFFFFFu, flat = 0xFFFF8080u;  // RGBA bytes, little-endian
        const void* white_mip[1] = {&white};
        const void* flat_mip[1] = {&flat};
        white_ = create_texture(1, 1, 1, TextureFormat::RGBA8, white_mip).index() - kMaxTargets;
        flat_normal_ = create_texture(1, 1, 1, TextureFormat::RGBA8, flat_mip).index() - kMaxTargets;
        gl_.glCreateBuffers(1, &light_ubo_);
        const LightSetup defaults = default_lights();
        gl_.glNamedBufferStorage(light_ubo_, sizeof defaults, &defaults, GL_DYNAMIC_STORAGE_BIT);
        // Shadow map slot 0: a 1x1 map at full depth, bound whenever no light casts shadows.
        create_shadow_map(1);
        const f32 far_depth = 1.0f;
        gl_.glTextureSubImage2D(shadow_maps_[0].texture, 0, 0, 0, 1, 1, GL_DEPTH_COMPONENT, GL_FLOAT, &far_depth);
        shadow_texture_ = local_shadow_texture_ = shadow_maps_[0].texture;
        line_mvp_ = gl_.glGetUniformLocation(line_program_, "u_mvp");

        gl_.glCreateVertexArrays(1, &vao_);  // core profile needs a bound VAO even without vertex buffers
        gl_.glCreateVertexArrays(1, &mesh_vao_);
        attribute(mesh_vao_, 0, 3, offsetof(MeshVertex, position));
        attribute(mesh_vao_, 1, 3, offsetof(MeshVertex, normal));
        attribute(mesh_vao_, 2, 2, offsetof(MeshVertex, uv));
        attribute(mesh_vao_, 5, 2, offsetof(MeshVertex, lightmap_uv));
        gl_.glCreateVertexArrays(1, &skinned_vao_);
        attribute(skinned_vao_, 0, 3, offsetof(SkinnedVertex, position));
        attribute(skinned_vao_, 1, 3, offsetof(SkinnedVertex, normal));
        attribute(skinned_vao_, 2, 2, offsetof(SkinnedVertex, uv));
        gl_.glEnableVertexArrayAttrib(skinned_vao_, 3);
        gl_.glVertexArrayAttribIFormat(skinned_vao_, 3, 4, GL_UNSIGNED_BYTE, offsetof(SkinnedVertex, joints));
        gl_.glVertexArrayAttribBinding(skinned_vao_, 3, 0);
        gl_.glEnableVertexArrayAttrib(skinned_vao_, 4);
        gl_.glVertexArrayAttribFormat(skinned_vao_, 4, 4, GL_UNSIGNED_BYTE, GL_TRUE, offsetof(SkinnedVertex, weights));
        gl_.glVertexArrayAttribBinding(skinned_vao_, 4, 0);
        gl_.glCreateBuffers(1, &param_ubo_);
        gl_.glNamedBufferStorage(param_ubo_, kMaxMaterialParams * 16, nullptr, GL_DYNAMIC_STORAGE_BIT);
        gl_.glCreateBuffers(1, &joint_ubo_);
        gl_.glNamedBufferStorage(joint_ubo_, kMaxJoints * 48, nullptr, GL_DYNAMIC_STORAGE_BIT);
        // GPU culling: all instances in, the visible ones out (read back as the instanced uniform block), the counter + draws.
        gl_.glCreateBuffers(1, &cull_in_);
        gl_.glNamedBufferStorage(cull_in_, kMaxCulledInstances * 48, nullptr, GL_DYNAMIC_STORAGE_BIT);
        gl_.glCreateBuffers(1, &cull_out_);
        gl_.glNamedBufferStorage(cull_out_, 4 * kMaxCulledInstances * 48, nullptr, 0);  // each LOD's rows
        gl_.glCreateBuffers(1, &cull_args_);
        gl_.glNamedBufferStorage(cull_args_, 16 + 4 * (kMaxCulledInstances / kMaxJoints) * 20, nullptr, 0);
        gl_.glCreateBuffers(1, &cull_ubo_);
        gl_.glNamedBufferStorage(cull_ubo_, sizeof(CullConstants), nullptr, GL_DYNAMIC_STORAGE_BIT);
        gl_.glCreateVertexArrays(1, &line_vao_);
        attribute(line_vao_, 0, 3, offsetof(LineVertex, position));
        attribute(line_vao_, 1, 4, offsetof(LineVertex, color));
        std::string sky_fragment = kMeshFragmentShader;
        sky_fragment.insert(sky_fragment.find('\n') + 1, "#define SKY\n");
        sky_program_ = link(kSkyVertexShader, sky_fragment.c_str());
        if (!sky_program_) return false;
        sky_mvp_ = gl_.glGetUniformLocation(sky_program_, "u_mvp");
        sky_camera_ = gl_.glGetUniformLocation(sky_program_, "u_camera");
        sky_values_ = gl_.glGetUniformLocation(sky_program_, "u_sky");
        ui_program_ = link(kUiVertexShader, kUiFragmentShader);
        if (!ui_program_) return false;
        ui_draw_ = gl_.glGetUniformLocation(ui_program_, "u_draw");
        gl_.glCreateBuffers(1, &ui_ibo_);
        gl_.glNamedBufferStorage(ui_ibo_, kUiIndexBytes, nullptr, GL_DYNAMIC_STORAGE_BIT);
        gl_.glCreateVertexArrays(1, &ui_vao_);
        attribute(ui_vao_, 0, 2, offsetof(UiVertex, position));
        gl_.glEnableVertexArrayAttrib(ui_vao_, 1);
        gl_.glVertexArrayAttribFormat(ui_vao_, 1, 4, GL_UNSIGNED_BYTE, GL_TRUE, offsetof(UiVertex, color));
        gl_.glVertexArrayAttribBinding(ui_vao_, 1, 0);
        attribute(ui_vao_, 2, 2, offsetof(UiVertex, uv));
        particle_program_ = link(kParticleVertexShader, kParticleFragmentShader);
        if (!particle_program_) return false;
        particle_mvp_ = gl_.glGetUniformLocation(particle_program_, "u_mvp");
        particle_hdr_ = gl_.glGetUniformLocation(particle_program_, "u_hdr");
        particle_soft_ = gl_.glGetUniformLocation(particle_program_, "u_soft");
        const char* post_defines[kPostPrograms] = {"#define PREFILTER\n", "#define DOWN\n", "#define UP\n", "#define COMPOSITE\n", "#define FXAA\n",
                                                   "#define AO\n", "#define AO_APPLY\n", "#define TAA\n", "#define DOF\n", "#define SSR\n",
                                                   "#define METER\n", "#define EXPOSE\n", "#define OUTLINE\n", "#define MOTION\n", "#define VELOCITY\n"};
        for (u32 i = 0; i < kPostPrograms; ++i) {
            std::string fragment = kPostFragmentShader;
            fragment.insert(fragment.find('\n') + 1, post_defines[i]);
            post_programs_[i] = link(kPostVertexShader, fragment.c_str());
            if (!post_programs_[i]) return false;
            post_uniforms_[i] = gl_.glGetUniformLocation(post_programs_[i], "u_post");
        }
        gl_.glCreateBuffers(1, &particle_vbo_);
        gl_.glNamedBufferStorage(particle_vbo_, kParticleRingBytes, nullptr, GL_DYNAMIC_STORAGE_BIT);
        gl_.glCreateVertexArrays(1, &particle_vao_);
        attribute(particle_vao_, 0, 3, offsetof(ParticleVertex, position));
        attribute(particle_vao_, 1, 4, offsetof(ParticleVertex, color));
        attribute(particle_vao_, 2, 2, offsetof(ParticleVertex, uv));
        return true;
    }

