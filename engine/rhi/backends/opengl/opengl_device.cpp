    TextureHandle create_shadow_map(u32 size) override {
        u32 slot = 0;
        while (slot < kMaxShadowMaps && shadow_maps_[slot].texture) ++slot;
        if (slot == kMaxShadowMaps || size == 0) return {};
        ShadowMap& m = shadow_maps_[slot];
        gl_.glCreateTextures(GL_TEXTURE_2D, 1, &m.texture);
        gl_.glTextureStorage2D(m.texture, 1, GL_DEPTH_COMPONENT32F, static_cast<GLsizei>(size), static_cast<GLsizei>(size));
        gl_.glTextureParameteri(m.texture, GL_TEXTURE_MIN_FILTER, GL_LINEAR);  // with compare mode: 2x2 filtered compare
        gl_.glTextureParameteri(m.texture, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
        gl_.glTextureParameteri(m.texture, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
        gl_.glTextureParameteri(m.texture, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
        gl_.glTextureParameteri(m.texture, GL_TEXTURE_COMPARE_MODE, GL_COMPARE_REF_TO_TEXTURE);
        gl_.glTextureParameteri(m.texture, GL_TEXTURE_COMPARE_FUNC, GL_LEQUAL);
        gl_.glCreateFramebuffers(1, &m.fbo);
        gl_.glNamedFramebufferTexture(m.fbo, GL_DEPTH_ATTACHMENT, m.texture, 0);
        gl_.glNamedFramebufferDrawBuffer(m.fbo, GL_NONE);
        gl_.glNamedFramebufferReadBuffer(m.fbo, GL_NONE);
        m.size = size;
        return TextureHandle::make(kMaxTargets + kMaxTextures + slot, m.generation);
    }

    void clear_shadow_viewport() override {
        if (!in_shadow_pass_) return;
        glDepthMask(GL_TRUE);
        glClearDepth(1.0);
        glClear(GL_DEPTH_BUFFER_BIT);  // set_viewport's scissor keeps it to the tile
    }

    void begin_shadow_pass(TextureHandle handle, bool clear) override {
        const ShadowMap* m = lookup_shadow(handle);
        if (!m) return;
        gl_.glBindFramebuffer(GL_FRAMEBUFFER, m->fbo);
        target_height_ = m->size;
        glDisable(GL_SCISSOR_TEST);
        glViewport(0, 0, static_cast<GLsizei>(m->size), static_cast<GLsizei>(m->size));
        glDepthMask(GL_TRUE);
        glClearDepth(1.0);
        if (clear) glClear(GL_DEPTH_BUFFER_BIT);
        glEnable(GL_DEPTH_TEST);
        glEnable(GL_POLYGON_OFFSET_FILL);
        glPolygonOffset(2.0f, 1.0f);  // against shadow acne on slopes; the shader adds a normal offset
        glEnable(GL_DEPTH_CLAMP);     // casters behind the light's near plane still cast (pancaking)
        in_shadow_pass_ = true;
    }

    void draw_shadow_caster(BufferHandle vertices, BufferHandle indices, u32 index_count, const f32 light_mvp[16], const f32* joint_rows,
                            u32 joint_count, const ShadowCutout* cutout) override {
        const Buffer* vb = lookup(vertices);
        const Buffer* ib = lookup(indices);
        if (!vb || !ib || !in_shadow_pass_) return;
        const bool skinned = joint_rows && joint_count;
        if (skinned) upload_joints(joint_rows, joint_count);
        const Texture* cut_tex = cutout ? lookup_texture(cutout->texture) : nullptr;
        const int variant = (skinned ? 1 : 0) + (cut_tex ? 2 : 0);  // plain, skinned, cut-out, skinned cut-out
        const GLuint programs[4] = {shadow_program_, skinned_shadow_program_, cutout_shadow_program_[0], cutout_shadow_program_[1]};
        const GLint mvps[4] = {shadow_mvp_, skinned_shadow_mvp_, cutout_shadow_mvp_[0], cutout_shadow_mvp_[1]};
        gl_.glUseProgram(programs[variant]);
        gl_.glUniformMatrix4fv(mvps[variant], 1, GL_FALSE, light_mvp);
        if (cut_tex) {
            const f32 cut[4] = {cutout->cutoff, cutout->alpha, cutout->uv_scale[0], cutout->uv_scale[1]};
            gl_.glUniform4fv(cutout_shadow_cut_[skinned ? 1 : 0], 1, cut);
            gl_.glBindTextureUnit(0, cut_tex->id);
        }
        const GLuint vao = skinned ? skinned_vao_ : mesh_vao_;
        gl_.glVertexArrayVertexBuffer(vao, 0, vb->id, 0, skinned ? sizeof(SkinnedVertex) : sizeof(MeshVertex));
        gl_.glVertexArrayElementBuffer(vao, ib->id);
        gl_.glBindVertexArray(vao);
        glDrawElements(GL_TRIANGLES, static_cast<GLsizei>(index_count), GL_UNSIGNED_INT, nullptr);
    }

    void draw_shadow_instances(BufferHandle vertices, BufferHandle indices, u32 index_count, const f32 view_proj[16], const f32* rows, u32 count,
                               const f32* bounds_min, const f32* bounds_max) override {
        const Buffer* vb = lookup(vertices);
        const Buffer* ib = lookup(indices);
        if (!vb || !ib || !in_shadow_pass_ || !rows || !count) return;
        MeshDraw cull;  // with bounds, culled against the light's view on the GPU
        cull.indices = indices;
        cull.index_count = index_count;
        std::memcpy(cull.mvp, view_proj, sizeof cull.mvp);
        cull.instance_rows = rows;
        cull.instance_count = count;
        if (bounds_min && bounds_max) {
            std::memcpy(cull.local_bounds_min, bounds_min, sizeof cull.local_bounds_min);
            std::memcpy(cull.local_bounds_max, bounds_max, sizeof cull.local_bounds_max);
        }
        const u32 batches = (count + kMaxJoints - 1) / kMaxJoints;
        const bool culled = bounds_min && bounds_max && run_culling(cull, batches);
        gl_.glUseProgram(instanced_shadow_program_);
        gl_.glUniformMatrix4fv(instanced_shadow_mvp_, 1, GL_FALSE, view_proj);
        gl_.glVertexArrayVertexBuffer(mesh_vao_, 0, vb->id, 0, sizeof(MeshVertex));
        gl_.glVertexArrayElementBuffer(mesh_vao_, ib->id);
        gl_.glBindVertexArray(mesh_vao_);
        if (culled) {
            draw_culled(cull, batches, mesh_vao_);
            return;
        }
        for (u32 first = 0; first < count; first += kMaxJoints) {  // the rows' buffer holds 256 copies a call
            const u32 n = count - first < kMaxJoints ? count - first : kMaxJoints;
            upload_joints(rows + first * 12, n);
            gl_.glDrawElementsInstanced(GL_TRIANGLES, static_cast<GLsizei>(index_count), GL_UNSIGNED_INT, nullptr, static_cast<GLsizei>(n));
        }
    }

    void end_shadow_pass() override {
        if (!in_shadow_pass_) return;
        in_shadow_pass_ = false;
        glDisable(GL_POLYGON_OFFSET_FILL);
        glDisable(GL_DEPTH_CLAMP);
        set_render_target({}, nullptr);  // back to the window
    }

