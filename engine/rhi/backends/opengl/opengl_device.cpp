// Same shading as the HLSL in the D3D12 backend (keep them in step).
constexpr char kMeshFragmentShader[] = R"(#version 460 core
uniform vec4 u_color;
uniform vec4 u_mat[2];   // metallic, roughness, emissive.rg | emissive.b, camera.xyz
uniform vec2 u_flags;    // unlit, has normal map
uniform float u_time;    // Material Graph Time
struct Light { vec4 pos_type; vec4 dir_range; vec4 color_inner; vec4 spot; };
layout(std140, binding = 1) uniform Lights {
    float exposure; uint light_count; vec2 pad0; vec4 sky_color; vec4 ground; Light lights[16];
    mat4 shadow_vp[4]; vec4 shadow_tile[4]; vec4 shadow_split; vec4 shadow_info;
    mat4 local_vp[16]; vec4 local_tile[16];
};
layout(binding = 3) uniform sampler2DShadow shadow_tex;
layout(binding = 4) uniform sampler2DShadow local_shadow_tex;
float sun_shadow(vec3 wpos, vec3 n, vec3 cam) {
    float dist = length(wpos - cam);
    int count = int(shadow_info.x);
    int c = 0;
    while (c + 1 < count && dist > shadow_split[c]) ++c;
    if (dist > shadow_split[count - 1]) return 1.0;
    vec4 s = shadow_vp[c] * vec4(wpos + n * shadow_info.w * (1.0 + float(c)), 1.0);
    vec2 uv = s.xy * 0.5 + 0.5;  // GL textures start at the bottom row
    if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0))) || s.z > 1.0) return 1.0;
    // Tiles are given top-left; in GL the atlas's rows run bottom-up.
    vec2 origin = vec2(shadow_tile[c].x, 1.0 - shadow_tile[c].y - shadow_tile[c].z);
    uv = origin + uv * shadow_tile[c].z;
    vec2 lo = origin + shadow_info.z, hi = origin + shadow_tile[c].z - shadow_info.z;
    float lit = 0.0;
    for (int y = -1; y <= 1; ++y)
        for (int x = -1; x <= 1; ++x) lit += texture(shadow_tex, vec3(clamp(uv + vec2(x, y) * shadow_info.z, lo, hi), s.z));
    return lit / 9.0;
}
float local_shadow(Light L, vec3 wpos, vec3 n) {
    int tile = int(L.spot.y);
    vec3 d = wpos - L.pos_type.xyz;
    if (L.pos_type.w < 1.5) {
        vec3 a = abs(d);
        tile += a.x >= a.y && a.x >= a.z ? (d.x > 0.0 ? 0 : 1) : a.y >= a.z ? (d.y > 0.0 ? 2 : 3) : (d.z > 0.0 ? 4 : 5);
    }
    vec4 s = local_vp[tile] * vec4(wpos + n * (L.spot.z * length(d)), 1.0);
    s.xyz /= s.w;
    vec2 uv = s.xy * 0.5 + 0.5;
    if (any(lessThan(uv, vec2(0.0))) || any(greaterThan(uv, vec2(1.0))) || s.z > 1.0 || s.z < 0.0) return 1.0;
    vec2 origin = vec2(local_tile[tile].x, 1.0 - local_tile[tile].y - local_tile[tile].z);
    uv = origin + uv * local_tile[tile].z;
    float texel = 1.0 / 4096.0;
    vec2 lo = origin + texel, hi = origin + local_tile[tile].z - texel;
    float lit = 0.0;
    for (int y = -1; y <= 1; ++y)
        for (int x = -1; x <= 1; ++x) lit += texture(local_shadow_tex, vec3(clamp(uv + vec2(x, y) * texel, lo, hi), s.z));
    return lit / 9.0;
}
layout(binding = 0) uniform sampler2D base_tex;
layout(binding = 1) uniform sampler2D normal_tex;
layout(binding = 2) uniform sampler2D orm_tex;
in vec3 v_normal;
in vec3 v_wpos;
in vec2 v_uv;
out vec4 o_color;
//@MATERIAL
const float PI = 3.14159265;
vec3 to_srgb(vec3 c) { c = clamp(c, 0.0, 1.0); return mix(c * 12.92, 1.055 * pow(c, vec3(1.0 / 2.4)) - 0.055, step(0.0031308, c)); }
vec3 perturb_normal(vec3 n, vec3 wpos, vec2 uv, vec3 tn) {
    vec3 dp1 = dFdx(wpos), dp2 = dFdy(wpos);
    vec2 duv1 = dFdx(uv), duv2 = dFdy(uv);
    vec3 dp2perp = cross(dp2, n), dp1perp = cross(n, dp1);
    vec3 t = dp2perp * duv1.x + dp1perp * duv2.x;
    vec3 b = dp2perp * duv1.y + dp1perp * duv2.y;
    float inv = inversesqrt(max(max(dot(t, t), dot(b, b)), 1e-12));
    return normalize(t * inv * tn.x + b * inv * tn.y + n * tn.z);
}
void main() {
    vec3 n = normalize(v_normal) * (gl_FrontFacing ? 1.0 : -1.0);
#ifdef LSD_MATERIAL
    MaterialIn mi;
    mi.uv = vec3(v_uv, 0.0); mi.wpos = v_wpos; mi.normal = n; mi.view = normalize(u_mat[1].yzw - v_wpos); mi.time = u_time;
    Surface surf = material_main(mi);
    vec4 base = vec4(surf.base_color * u_color.rgb, u_color.a);
    if (u_flags.x > 0.5) { o_color = vec4(to_srgb(base.rgb), base.a); return; }
    n = perturb_normal(n, v_wpos, v_uv, surf.normal);
    float metallic = clamp(surf.metallic, 0.0, 1.0);
    float roughness = clamp(surf.roughness, 0.04, 1.0);
    float ao = clamp(surf.ao, 0.0, 1.0);
    vec3 emissive = surf.emissive;
#else
    vec4 base = u_color * texture(base_tex, v_uv);
    if (u_flags.x > 0.5) { o_color = vec4(to_srgb(base.rgb), base.a); return; }
    if (u_flags.y > 0.5) n = perturb_normal(n, v_wpos, v_uv, texture(normal_tex, v_uv).xyz * 2.0 - 1.0);
    vec3 orm = texture(orm_tex, v_uv).rgb;
    float metallic = clamp(u_mat[0].x * orm.b, 0.0, 1.0);
    float roughness = clamp(u_mat[0].y * orm.g, 0.04, 1.0);
    float ao = orm.r;
    vec3 emissive = vec3(u_mat[0].zw, u_mat[1].x);
#endif
    vec3 v = normalize(u_mat[1].yzw - v_wpos);
    float ndv = max(dot(n, v), 1e-4);
    vec3 f0 = mix(vec3(0.04), base.rgb, metallic);
    float a2 = roughness * roughness * roughness * roughness;
    float k = (roughness + 1.0) * (roughness + 1.0) / 8.0;
    vec3 lit = vec3(0.0);
    for (uint li = 0u; li < light_count; ++li) {
        Light L = lights[li];
        vec3 l;
        float atten = 1.0;
        if (L.pos_type.w < 0.5) {
            l = -L.dir_range.xyz;
        } else {
            vec3 to = L.pos_type.xyz - v_wpos;
            float dist2 = max(dot(to, to), 1e-4);
            l = to * inversesqrt(dist2);
            float r = dist2 / (L.dir_range.w * L.dir_range.w);
            float window = clamp(1.0 - r * r, 0.0, 1.0);
            atten = window * window / dist2;
            if (L.pos_type.w > 1.5) atten *= clamp((dot(-l, L.dir_range.xyz) - L.spot.x) / max(L.color_inner.w - L.spot.x, 1e-4), 0.0, 1.0);
        }
        float ndl = clamp(dot(n, l), 0.0, 1.0);
        if (ndl <= 0.0 || atten <= 0.0) continue;
        if (float(li) == shadow_info.y) atten *= sun_shadow(v_wpos, n, u_mat[1].yzw);
        else if (L.spot.y >= 0.0) atten *= local_shadow(L, v_wpos, n);
        vec3 h = normalize(v + l);
        float ndh = clamp(dot(n, h), 0.0, 1.0), vdh = clamp(dot(v, h), 0.0, 1.0);
        float d = a2 / (PI * pow(ndh * ndh * (a2 - 1.0) + 1.0, 2.0));
        float g = (ndl / (ndl * (1.0 - k) + k)) * (ndv / (ndv * (1.0 - k) + k));
        vec3 f = f0 + (1.0 - f0) * pow(1.0 - vdh, 5.0);
        vec3 specular = d * g * f / max(4.0 * ndl * ndv, 1e-4);
        vec3 diffuse = (1.0 - f) * (1.0 - metallic) * base.rgb / PI;
        lit += (diffuse + specular) * L.color_inner.xyz * ndl * atten;
    }
    vec3 sky = mix(ground.rgb, sky_color.rgb, n.z * 0.5 + 0.5);
    vec3 env_f = f0 + (max(vec3(1.0 - roughness), f0) - f0) * pow(1.0 - ndv, 5.0);
    lit += (base.rgb * (1.0 - metallic) * (1.0 - env_f) + env_f * (1.0 - roughness * 0.7)) * sky * ao;
    lit += emissive;
    o_color = vec4(to_srgb(lit * exposure), base.a);
}
)";

