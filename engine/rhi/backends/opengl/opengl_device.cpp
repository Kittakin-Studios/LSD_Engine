    explicit OpenGLDevice(const DeviceDesc& desc) : validation_(desc.enable_validation) {
        if (desc.adapter_override >= 0) {
            LSD_LOG_WARN("opengl", "-gpu is ignored: OpenGL uses the GPU chosen by the driver / Windows graphics settings.");
        }
        // Context attributes must be set before the window is created.
        SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 4);
        SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 6);
        SDL_GL_SetAttribute(SDL_GL_CONTEXT_PROFILE_MASK, SDL_GL_CONTEXT_PROFILE_CORE);
        SDL_GL_SetAttribute(SDL_GL_CONTEXT_FLAGS, validation_ ? SDL_GL_CONTEXT_DEBUG_FLAG : 0);
        SDL_GL_SetAttribute(SDL_GL_DOUBLEBUFFER, 1);
        SDL_GL_SetAttribute(SDL_GL_DEPTH_SIZE, 24);
    }

    ~OpenGLDevice() override {
        if (!context_) return;
        if (debug_ui_) ImGui_ImplOpenGL3_Shutdown();
        for (GLuint program : {program_, mesh_.id, skinned_program_.id, line_program_, shadow_program_, skinned_shadow_program_, particle_program_, sky_program_, ui_program_, post_programs_[0], post_programs_[1], post_programs_[2],
                               post_programs_[3], post_programs_[4]}) {
            if (program) gl_.glDeleteProgram(program);
        }
        for (const PostShader& post : post_shaders_) {
            if (post.program) gl_.glDeleteProgram(post.program);
        }
        if (particle_vbo_) gl_.glDeleteBuffers(1, &particle_vbo_);
        if (param_ubo_) gl_.glDeleteBuffers(1, &param_ubo_);
        for (GLuint* b : {&cull_in_, &cull_out_, &cull_args_, &cull_ubo_}) {
            if (*b) gl_.glDeleteBuffers(1, b);
        }
        if (cull_program_) gl_.glDeleteProgram(cull_program_);
        if (hiz_program_) gl_.glDeleteProgram(hiz_program_);
        if (morph_program_) gl_.glDeleteProgram(morph_program_);
        if (gpu_sim_program_) gl_.glDeleteProgram(gpu_sim_program_);
        if (gpu_sprite_program_) gl_.glDeleteProgram(gpu_sprite_program_);
        if (gpu_particle_ubo_) gl_.glDeleteBuffers(1, &gpu_particle_ubo_);
        if (morph_weights_) gl_.glDeleteBuffers(1, &morph_weights_);
        if (hiz_texture_) glDeleteTextures(1, &hiz_texture_);
        if (ui_ibo_) gl_.glDeleteBuffers(1, &ui_ibo_);
        if (ui_vao_) gl_.glDeleteVertexArrays(1, &ui_vao_);
        for (MaterialShader& m : material_shaders_) {
            if (m.mesh.id) gl_.glDeleteProgram(m.mesh.id);
            if (m.skinned.id) gl_.glDeleteProgram(m.skinned.id);
        }
        for (GLuint vao : {vao_, mesh_vao_, skinned_vao_, line_vao_, particle_vao_}) {
            if (vao) gl_.glDeleteVertexArrays(1, &vao);
        }
        for (Buffer& b : buffers_) {
            if (b.id) gl_.glDeleteBuffers(1, &b.id);
        }
        for (u32 i = 0; i < kMaxTargets; ++i) release_target(targets_[i]);
        SDL_GL_DestroyContext(context_);
    }

    Backend backend() const override { return Backend::OpenGL; }
    const AdapterInfo& adapter() const override { return info_; }

    MemoryBudget query_memory_budget() const override {
        MemoryBudget budget{};
        GLint kib[4] = {};
        if (has_nvx_memory_info_) {
            glGetIntegerv(kGpuMemoryTotalNvx, kib);
            budget.budget_bytes = static_cast<u64>(kib[0]) * KiB;
            glGetIntegerv(kGpuMemoryAvailableNvx, kib);
            budget.usage_bytes = budget.budget_bytes - static_cast<u64>(kib[0]) * KiB;
        } else if (has_ati_meminfo_) {
            // AMD only reports free memory; treat it as the budget with no known usage.
            glGetIntegerv(kTextureFreeMemoryAti, kib);
            budget.budget_bytes = static_cast<u64>(kib[0]) * KiB;
        }
        return budget;
    }

    bool create_swapchain(SDL_Window* window, u32 width, u32 height) override {
        window_ = window;
        context_ = SDL_GL_CreateContext(window);
        if (!context_) {
            LSD_LOG_ERROR("opengl", "Could not create an OpenGL 4.6 core context: %s", SDL_GetError());
            return false;
        }
        SDL_GL_MakeCurrent(window, context_);
        SDL_GL_SetSwapInterval(1);  // vsync
        if (!gl_.load()) return false;

        const char* renderer = reinterpret_cast<const char*>(glGetString(GL_RENDERER));
        const char* vendor = reinterpret_cast<const char*>(glGetString(GL_VENDOR));
        SDL_strlcpy(info_.name, renderer ? renderer : "unknown", sizeof info_.name);
        info_.vendor = vendor_from_string(vendor ? vendor : "");
        LSD_LOG_INFO("opengl", "%s (%s)", info_.name, reinterpret_cast<const char*>(glGetString(GL_VERSION)));

        GLint extension_count = 0;
        glGetIntegerv(GL_NUM_EXTENSIONS, &extension_count);
        for (GLint i = 0; i < extension_count; ++i) {
            const char* ext = reinterpret_cast<const char*>(gl_.glGetStringi(GL_EXTENSIONS, static_cast<GLuint>(i)));
            if (std::strcmp(ext, "GL_NVX_gpu_memory_info") == 0) has_nvx_memory_info_ = true;
            if (std::strcmp(ext, "GL_ATI_meminfo") == 0) has_ati_meminfo_ = true;
            if (std::strcmp(ext, "GL_EXT_texture_compression_s3tc") == 0) has_s3tc_ = true;
            if (std::strcmp(ext, "GL_EXT_texture_sRGB") == 0 || std::strcmp(ext, "GL_EXT_texture_sRGB_S3TC") == 0) has_srgb_s3tc_ = true;
            if (std::strcmp(ext, "GL_NV_mesh_shader") == 0 || std::strcmp(ext, "GL_EXT_mesh_shader") == 0) info_.supports_mesh_shaders = true;
        }
        // VRAM size for preset selection. AMD only reports free memory, which at startup is close to the total.
        GLint kib[4] = {};
        if (has_nvx_memory_info_) glGetIntegerv(kGpuMemoryTotalNvx, kib);
        else if (has_ati_meminfo_) glGetIntegerv(kTextureFreeMemoryAti, kib);
        info_.dedicated_vram_bytes = static_cast<u64>(kib[0]) * KiB;

        if (validation_) {
            glEnable(GL_DEBUG_OUTPUT);
            glEnable(GL_DEBUG_OUTPUT_SYNCHRONOUS);
            gl_.glDebugMessageCallback(debug_callback, nullptr);
            LSD_LOG_INFO("opengl", "Debug output enabled.");
        }

        // Same clip-space depth range (0..1) as D3D12 and Vulkan, so one projection matrix fits all.
        gl_.glClipControl(GL_LOWER_LEFT, GL_ZERO_TO_ONE);
        glDepthFunc(GL_LEQUAL);

        width_ = width;
        height_ = height;
        return create_programs();
    }

    void resize_swapchain(u32 width, u32 height) override {
        if (width == 0 || height == 0) return;
        width_ = width;
        height_ = height;
    }

    BufferHandle create_buffer(BufferUsage usage, const void* data, u64 size) override {
        u32 slot = 0;
        while (slot < kMaxBuffers && buffers_[slot].id) ++slot;
        if (slot == kMaxBuffers || size == 0 || !data) {
            LSD_LOG_ERROR("opengl", "create_buffer failed: table full (%u) or empty data.", kMaxBuffers);
            return {};
        }
        Buffer& b = buffers_[slot];
        gl_.glCreateBuffers(1, &b.id);
        gl_.glNamedBufferStorage(b.id, static_cast<GLsizeiptr>(size), data, 0);  // immutable
        b.usage = usage;
        return BufferHandle::make(slot, b.generation);
    }

    void destroy_buffer(BufferHandle handle) override {
        Buffer* b = lookup(handle);
        if (!b) return;
        gl_.glDeleteBuffers(1, &b->id);  // GL defers the real release until the GPU is done
        b->id = 0;
        ++b->generation;
    }

