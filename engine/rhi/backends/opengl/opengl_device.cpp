        if (!vb) return;
        glEnable(GL_DEPTH_TEST);
        glDepthMask(GL_TRUE);
        gl_.glUseProgram(line_program_);
        gl_.glUniformMatrix4fv(line_mvp_, 1, GL_FALSE, mvp);
        gl_.glVertexArrayVertexBuffer(line_vao_, 0, vb->id, 0, sizeof(LineVertex));
