    bool supports_bc() const override { return has_s3tc_ && has_srgb_s3tc_; }
    TextureHandle create_texture(u32 width, u32 height, u32 mip_count, TextureFormat format, const void* const* mips) override {
        if (is_block_compressed(format) && !supports_bc()) return {};
        u32 slot = 0;
        while (slot < kMaxTextures && textures_[slot].id) ++slot;
        if (slot == kMaxTextures || width == 0 || height == 0 || mip_count == 0 || mip_count > kMaxMips) {
            LSD_LOG_ERROR("opengl", "create_texture failed: table full (%u), zero size or bad mip count.", kMaxTextures);
            return {};
        }
        Texture& t = textures_[slot];
        gl_.glCreateTextures(GL_TEXTURE_2D, 1, &t.id);
        // S3TC (EXT_texture_compression_s3tc / EXT_texture_sRGB): BC1 = RGBA DXT1, BC3 = DXT5.
        GLenum internal = format == TextureFormat::RGBA8_sRGB ? GL_SRGB8_ALPHA8 : GL_RGBA8;
        switch (format) {
            case TextureFormat::BC1: internal = 0x83F1; break;       // GL_COMPRESSED_RGBA_S3TC_DXT1_EXT
            case TextureFormat::BC1_sRGB: internal = 0x8C4D; break;  // GL_COMPRESSED_SRGB_ALPHA_S3TC_DXT1_EXT
            case TextureFormat::BC3: internal = 0x83F3; break;       // GL_COMPRESSED_RGBA_S3TC_DXT5_EXT
            case TextureFormat::BC3_sRGB: internal = 0x8C4F; break;  // GL_COMPRESSED_SRGB_ALPHA_S3TC_DXT5_EXT
            case TextureFormat::BC5: internal = 0x8DBD; break;       // GL_COMPRESSED_RG_RGTC2 (core since 3.0)
            case TextureFormat::RGBA16F: internal = GL_RGBA16F; break;
            default: break;
        }
        gl_.glTextureStorage2D(t.id, static_cast<GLsizei>(mip_count), internal, static_cast<GLsizei>(width), static_cast<GLsizei>(height));
        glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
        for (u32 m = 0; m < mip_count; ++m) {
            const u32 w = width >> m ? width >> m : 1, h = height >> m ? height >> m : 1;
            if (is_block_compressed(format)) {
                gl_.glCompressedTextureSubImage2D(t.id, static_cast<GLint>(m), 0, 0, static_cast<GLsizei>(w), static_cast<GLsizei>(h), internal,
                                                  static_cast<GLsizei>(texture_bytes(format, w, h)), mips[m]);
            } else {
                gl_.glTextureSubImage2D(t.id, static_cast<GLint>(m), 0, 0, static_cast<GLsizei>(w), static_cast<GLsizei>(h), GL_RGBA,
                                        format == TextureFormat::RGBA16F ? GL_HALF_FLOAT : GL_UNSIGNED_BYTE, mips[m]);
            }
        }
        gl_.glTextureParameteri(t.id, GL_TEXTURE_MIN_FILTER, mip_count > 1 ? GL_LINEAR_MIPMAP_LINEAR : GL_LINEAR);
        gl_.glTextureParameteri(t.id, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
        gl_.glTextureParameteri(t.id, GL_TEXTURE_WRAP_S, GL_REPEAT);
        gl_.glTextureParameteri(t.id, GL_TEXTURE_WRAP_T, GL_REPEAT);
        gl_.glTextureParameterf(t.id, kMaxAnisotropy, 8.0f);
        return TextureHandle::make(kMaxTargets + slot, t.generation);
    }

    TextureHandle create_render_target(u32 width, u32 height) override {
        u32 slot = 0;
        while (slot < kMaxTargets && targets_[slot].fbo) ++slot;
        if (slot == kMaxTargets || width == 0 || height == 0) {
            LSD_LOG_ERROR("opengl", "create_render_target failed: table full (%u) or zero size.", kMaxTargets);
            return {};
        }
        Target& t = targets_[slot];
        gl_.glCreateTextures(GL_TEXTURE_2D, 1, &t.color);
        gl_.glTextureStorage2D(t.color, 1, GL_RGBA16F, static_cast<GLsizei>(width), static_cast<GLsizei>(height));  // half float, as D3D12 / Vulkan (readback converts)
        gl_.glTextureParameteri(t.color, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
        gl_.glTextureParameteri(t.color, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
        gl_.glTextureParameteri(t.color, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);  // post-process taps stay inside
        gl_.glTextureParameteri(t.color, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
        gl_.glCreateTextures(GL_TEXTURE_2D, 1, &t.depth);  // a texture, not a renderbuffer: the post pass reads it
        gl_.glTextureStorage2D(t.depth, 1, GL_DEPTH_COMPONENT32F, static_cast<GLsizei>(width), static_cast<GLsizei>(height));
        gl_.glTextureParameteri(t.depth, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
        gl_.glTextureParameteri(t.depth, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
        gl_.glTextureParameteri(t.depth, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
        gl_.glTextureParameteri(t.depth, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
        gl_.glCreateFramebuffers(1, &t.fbo);
        gl_.glNamedFramebufferTexture(t.fbo, GL_COLOR_ATTACHMENT0, t.color, 0);
        gl_.glNamedFramebufferTexture(t.fbo, GL_DEPTH_ATTACHMENT, t.depth, 0);
        if (gl_.glCheckNamedFramebufferStatus(t.fbo, GL_FRAMEBUFFER) != GL_FRAMEBUFFER_COMPLETE) {
            LSD_LOG_ERROR("opengl", "Render target framebuffer is incomplete.");
            release_target(t);
            return {};
        }
        t.width = width;
        t.height = height;
        return TextureHandle::make(slot, t.generation);
    }

    void destroy_texture(TextureHandle handle) override {
        if (ShadowMap* shadow = lookup_shadow(handle)) {
            gl_.glDeleteFramebuffers(1, &shadow->fbo);
            glDeleteTextures(1, &shadow->texture);
            shadow->fbo = shadow->texture = 0;
            ++shadow->generation;
            return;
        }
        if (Texture* texture = lookup_texture(handle)) {
            glDeleteTextures(1, &texture->id);
            texture->id = 0;
            ++texture->generation;
            return;
        }
        Target* t = lookup(handle);
        if (!t) return;
        release_target(*t);  // GL defers the real release until the GPU is done
        ++t->generation;
    }

