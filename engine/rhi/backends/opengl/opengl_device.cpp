    // The Hi-Z (PostDraw::build_hiz): R32F, the farthest depth of each 2 x 2 down its mips; its view-projection.
    GLuint hiz_program_ = 0, hiz_texture_ = 0;
    GLint hiz_size_location_ = -1, hiz_level_location_ = -1;
